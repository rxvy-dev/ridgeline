#!/usr/bin/env python3
"""Generates src/font_atlas.h: the UI fonts baked into one atlas.

  font 0 - body text    : Barlow SemiBold                 (ASCII)
  font 1 - display text : Shippori Mincho B1 ExtraBold    (ASCII, an ink-brush serif)
  kanji                 : Shippori Mincho B1 ExtraBold    (the handful of Japanese characters the menus use)

Barlow is by Jeremy Tribby; Shippori Mincho B1 is by FONTDASU. Both SIL Open Font License 1.1
(assets/fonts/OFL.txt). Shippori is big (15 MB), so it isn't kept in the repo: it's fetched from the
google/fonts repository into tools/.fontcache the first time this runs.
Run from the repo root:  python3 tools/gen_font.py
"""
import os
import urllib.request
from PIL import Image, ImageDraw, ImageFont

CACHE = "tools/.fontcache"
SHIPPORI = os.path.join(CACHE, "ShipporiMinchoB1-ExtraBold.ttf")
if not os.path.exists(SHIPPORI):
    os.makedirs(CACHE, exist_ok=True)
    url = "https://raw.githubusercontent.com/google/fonts/main/ofl/shipporiminchob1/ShipporiMinchoB1-ExtraBold.ttf"
    print("fetching", url)
    urllib.request.urlretrieve(url, SHIPPORI)

FONTS = [("assets/fonts/Barlow-SemiBold.ttf", 48), (SHIPPORI, 58)]
# every Japanese character the UI prints; add to this list (and re-run) to use more
KANJI = sorted(set(
    "峠祭り走再開地図車庫販売塗装改造福引写真設定終了保存次戦家創作記録取込結果順位周時間速度一時停止勝新夜桜富士"
    "東京選決戻段円金銀銅第秒分旅並珍極伝説の山道日本典競技場出発到着休憩夢風花月星空海川森町村街"
    "家具宝箱賞品当選大吉小中凶運命挑戦記録更新最高速漂流周回短距離走破音画面操作補助言語天気北利技"))
KSIZE = 64
W, PAD = 1024, 3

glyphs, metrics = [], []
x, y, rowh = PAD, PAD, 0


def place(gw, gh):
    global x, y, rowh
    if x + gw + PAD > W:
        x, y, rowh = PAD, y + rowh + PAD, 0
    p = (x, y)
    x += gw + PAD
    rowh = max(rowh, gh)
    return p


for fi, (path, size) in enumerate(FONTS):
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    metrics.append((size, asc))
    for c in range(32, 127):
        l, t, r, b = font.getbbox(chr(c))
        gw, gh = max(1, r - l), max(1, b - t)
        gx, gy = place(gw, gh)
        glyphs.append((fi, font, chr(c), gx, gy, gw, gh, l, t, font.getlength(chr(c))))

kfont = ImageFont.truetype(SHIPPORI, KSIZE)
kglyphs = []
for ch in KANJI:
    l, t, r, b = kfont.getbbox(ch)
    gw, gh = max(1, r - l), max(1, b - t)
    gx, gy = place(gw, gh)
    kglyphs.append((kfont, ch, gx, gy, gw, gh, l, t, kfont.getlength(ch)))

H = 1
while H < y + rowh + PAD:
    H *= 2
img = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(img)
for (fi, font, ch, gx, gy, gw, gh, ox, oy, adv) in glyphs:
    d.text((gx - ox, gy - oy), ch, font=font, fill=255)
for (font, ch, gx, gy, gw, gh, ox, oy, adv) in kglyphs:
    d.text((gx - ox, gy - oy), ch, font=font, fill=255)
data = img.tobytes()

with open("src/font_atlas.h", "w") as f:
    f.write("// Generated by tools/gen_font.py - Barlow and Shippori Mincho B1 (SIL OFL 1.1, see assets/fonts/OFL.txt)\n#pragma once\n")
    f.write(f"#define FONT_ATLAS_W {W}\n#define FONT_ATLAS_H {H}\n#define FONT_COUNT {len(FONTS)}\n")
    f.write("static const int kFontSize[FONT_COUNT] = {" + ",".join(str(m[0]) for m in metrics) + "};\n")
    f.write("static const int kFontAscent[FONT_COUNT] = {" + ",".join(str(m[1]) for m in metrics) + "};\n")
    f.write("struct FontGlyph { short x, y, w, h, ox, oy; float adv; };\n")
    f.write("static const FontGlyph kFontGlyphs[FONT_COUNT][95] = {\n")
    for fi in range(len(FONTS)):
        f.write("  {\n")
        for (gfi, font, ch, gx, gy, gw, gh, ox, oy, adv) in glyphs:
            if gfi == fi:
                f.write(f"    {{{gx},{gy},{gw},{gh},{ox},{oy},{adv:.2f}f}},\n")
        f.write("  },\n")
    f.write("};\n")
    f.write(f"#define KANJI_COUNT {len(kglyphs)}\nstatic const int kKanjiSize = {KSIZE};\n")
    f.write("static const unsigned int kKanjiCode[KANJI_COUNT] = {" + ",".join(str(ord(g[1])) for g in kglyphs) + "};\n")
    f.write("static const FontGlyph kKanjiGlyph[KANJI_COUNT] = {\n")
    for (font, ch, gx, gy, gw, gh, ox, oy, adv) in kglyphs:
        f.write(f"    {{{gx},{gy},{gw},{gh},{ox},{oy},{adv:.2f}f}},\n")
    f.write("};\n")
    rle, i = [], 0
    while i < len(data):
        v, n = data[i], 1
        while i + n < len(data) and data[i + n] == v and n < 255:
            n += 1
        rle += [n, v]
        i += n
    f.write(f"static const unsigned int kFontRLESize = {len(rle)};\nstatic const unsigned char kFontRLE[] = {{\n")
    for k in range(0, len(rle), 32):
        f.write(",".join(map(str, rle[k:k + 32])) + ",\n")
    f.write("};\n")
print("atlas", W, H, "kanji", len(kglyphs), "rle bytes", len(rle))
