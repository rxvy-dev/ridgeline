#!/usr/bin/env python3
"""Generates src/font_atlas.h from a TTF font (default: DejaVu Sans Bold).

DejaVu fonts are released under the Bitstream Vera / DejaVu license, which
permits embedding. Run:  python3 tools/gen_font.py [font.ttf]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE = 40
W = 512
PAD = 2

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
glyphs = []
x, y, rowh = PAD, PAD, 0
for c in range(32, 127):
    ch = chr(c)
    bbox = font.getbbox(ch)  # l,t,r,b relative to origin (top = ascent line)
    gw, gh = max(1, bbox[2] - bbox[0]), max(1, bbox[3] - bbox[1])
    if x + gw + PAD > W:
        x = PAD
        y += rowh + PAD
        rowh = 0
    glyphs.append((c, x, y, gw, gh, bbox[0], bbox[1], font.getlength(ch)))
    x += gw + PAD
    rowh = max(rowh, gh)
H = 1
while H < y + rowh + PAD:
    H *= 2

img = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(img)
for (c, gx, gy, gw, gh, ox, oy, adv) in glyphs:
    d.text((gx - ox, gy - oy), chr(c), font=font, fill=255)

data = img.tobytes()
with open("src/font_atlas.h", "w") as f:
    f.write("// Generated by tools/gen_font.py from DejaVu Sans Bold (Bitstream Vera/DejaVu license)\n")
    f.write("#pragma once\n")
    f.write(f"#define FONT_ATLAS_W {W}\n#define FONT_ATLAS_H {H}\n#define FONT_SIZE {SIZE}\n#define FONT_ASCENT {ascent}\n")
    f.write("struct FontGlyph { short x, y, w, h, ox, oy; float adv; };\n")
    f.write("static const FontGlyph kFontGlyphs[95] = {\n")
    for (c, gx, gy, gw, gh, ox, oy, adv) in glyphs:
        f.write(f"  {{{gx},{gy},{gw},{gh},{ox},{oy},{adv:.2f}f}},\n")
    f.write("};\n")
    # simple RLE: pairs of (count, value)
    rle = []
    i = 0
    while i < len(data):
        v = data[i]
        n = 1
        while i + n < len(data) and data[i + n] == v and n < 255:
            n += 1
        rle += [n, v]
        i += n
    f.write(f"static const unsigned int kFontRLESize = {len(rle)};\n")
    f.write("static const unsigned char kFontRLE[] = {\n")
    for j in range(0, len(rle), 24):
        f.write(",".join(str(b) for b in rle[j:j + 24]) + ",\n")
    f.write("};\n")
print("atlas", W, H, "rle bytes", len(rle))
