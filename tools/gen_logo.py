#!/usr/bin/env python3
"""Draws the Ridgeline wordmark (white italic letters under a pink-to-orange ridge line)
and writes packaging/logo.png plus src/logo_data.h (zlib RGBA) for the game.
Run from the repo root:  python3 tools/gen_logo.py"""
import zlib
from PIL import Image, ImageDraw, ImageFont, ImageFilter

SS = 3                      # supersampling
W, H = 1600, 420
FONT = "assets/fonts/BarlowSemiCondensed-ExtraBoldItalic.ttf"
PINK, ORANGE = (236, 22, 128), (255, 120, 24)


def grad(w, h, a, b):
    g = Image.new("RGBA", (w, h))
    px = g.load()
    for x in range(w):
        t = x / max(1, w - 1)
        c = tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3)) + (255,)
        for y in range(h):
            px[x, y] = c
    return g


big = Image.new("RGBA", (W * SS, H * SS), (0, 0, 0, 0))
font = ImageFont.truetype(FONT, 250 * SS)
word = "RIDGELINE"
l, t, r, b = font.getbbox(word)
tw, th = r - l, b - t
x0 = (W * SS - tw) // 2 - l
y0 = int(150 * SS) - t
# letters, white
mask = Image.new("L", big.size, 0)
ImageDraw.Draw(mask).text((x0, y0), word, font=font, fill=255)
big.paste(Image.new("RGBA", big.size, (255, 255, 255, 255)), (0, 0), mask)

# the ridge: a sharp mountain line across the top of the word
left, right = x0 + l - 40 * SS, x0 + r + 30 * SS
base = y0 + t - 26 * SS
pts = [(0.00, 0.0), (0.10, -0.35), (0.17, -0.12), (0.30, -0.95), (0.40, -0.40), (0.47, -0.62),
       (0.60, -0.08), (0.72, -0.55), (0.80, -0.30), (0.90, -0.70), (1.00, 0.0)]
peak = 95 * SS
poly = [(left + (right - left) * px, base + py * peak) for px, py in pts]
lm = Image.new("L", big.size, 0)
ImageDraw.Draw(lm).line(poly, fill=255, width=17 * SS, joint="curve")
gimg = grad(big.width, big.height, PINK, ORANGE)
big.paste(gimg, (0, 0), lm)
# underline bar, same gradient, slanted
bar_y = y0 + b + 22 * SS
um = Image.new("L", big.size, 0)
sl = 12 * SS
ImageDraw.Draw(um).polygon([(left + 120 * SS + sl, bar_y), (right - 60 * SS + sl, bar_y), (right - 60 * SS, bar_y + 14 * SS), (left + 120 * SS, bar_y + 14 * SS)], fill=255)
big.paste(gimg, (0, 0), um)

logo = big.resize((W, H), Image.LANCZOS)
bbox = logo.getbbox()
logo = logo.crop((max(0, bbox[0] - 8), max(0, bbox[1] - 8), min(W, bbox[2] + 8), min(H, bbox[3] + 8)))
logo.save("packaging/logo.png")
raw = logo.tobytes()
z = zlib.compress(raw, 9)
with open("src/logo_data.h", "w") as f:
    f.write("// Generated by tools/gen_logo.py - Ridgeline wordmark, zlib-compressed RGBA\n#pragma once\n#include <cstdint>\n")
    f.write(f"static const int kLogoW = {logo.width}, kLogoH = {logo.height};\nstatic const unsigned kLogoZSize = {len(z)};\n")
    f.write("static const uint8_t kLogoZ[] = {\n")
    for k in range(0, len(z), 40):
        f.write(",".join(map(str, z[k:k + 40])) + ",\n")
    f.write("};\n")
print("logo", logo.size, "zlib", len(z))
